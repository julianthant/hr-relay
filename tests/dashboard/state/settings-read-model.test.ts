import assert from "node:assert/strict";
import { afterEach, it, vi } from "vitest";
import { createSettingsRead, SETTINGS_READS_LIMIT, settingsReadResource } from "../../../src/dashboard/state/settings-read-model.js";
import { dropKeptResults } from "../../../src/dashboard/state/async-resource.js";
import { ERROR_CATALOG } from "../../../src/models/failures/error-catalog.js";

afterEach(() => { vi.useRealTimers(); });
it("shares pending reads and retains exact verified data through refresh failure and timeout", async () => {
  vi.useFakeTimers();
  const resource = createSettingsRead<{ revision: number }>();
  const value = { revision: 7 }; resource.accept(value);
  const pending = Promise.withResolvers<typeof value>(); let calls = 0;
  const first = resource.read(() => { calls++; return pending.promise; }, "SETTINGS_INITIAL_READ_UNAVAILABLE");
  assert.equal(resource.read(() => { calls++; return pending.promise; }, "SETTINGS_INITIAL_READ_UNAVAILABLE"), first);
  assert.equal(calls, 1); assert.equal(resource.snapshot().value, value); assert.equal(resource.snapshot().state, "loading");
  const failed = first.catch((error: unknown) => error);
  await vi.advanceTimersByTimeAsync(10_000);
  const error = await failed; assert.ok(error instanceof Error);
  assert.equal(error.message, ERROR_CATALOG.SETTINGS_INITIAL_READ_UNAVAILABLE.text);
  assert.equal(resource.snapshot().value, value); assert.equal(resource.snapshot().state, "failed");
  pending.resolve({ revision: 8 }); await Promise.resolve(); assert.equal(resource.snapshot().value, value);
  await resource.read(() => Promise.reject(new Error("synthetic 503")), "SETTINGS_INITIAL_READ_UNAVAILABLE").catch(() => undefined);
  assert.equal(resource.snapshot().value, value); assert.equal(resource.snapshot().state, "failed");
});
it("hides replaced authority and cannot revive old A data through A to B to A", async () => {
  const client = {}, authorityA = {}, authorityB = {};
  const a = settingsReadResource<number>(client, authorityA, "actor-a:descriptor-a", "editor");
  a.accept(7);
  const pending = Promise.withResolvers<number>();
  const old = a.read(() => pending.promise, "SETTINGS_INITIAL_READ_UNAVAILABLE").catch((error: unknown) => error);
  const b = settingsReadResource<number>(client, authorityB, "actor-a:descriptor-a", "editor");
  assert.equal(b.snapshot().value, undefined);
  const nextA = settingsReadResource<number>(client, authorityA, "actor-a:descriptor-a", "editor");
  assert.notEqual(nextA, a); assert.equal(nextA.snapshot().value, undefined);
  pending.resolve(8); assert.ok(await old instanceof Error); assert.equal(a.snapshot().value, undefined); assert.equal(nextA.snapshot().value, undefined);
  const actor = settingsReadResource<number>(client, authorityA, "actor-b:descriptor-a", "editor");
  assert.equal(actor.snapshot().value, undefined);
  const descriptor = settingsReadResource<number>(client, authorityA, "actor-b:descriptor-b", "editor");
  assert.equal(descriptor.snapshot().value, undefined);
});
it("authoritative acceptance fences an older pending observation", async () => {
  const resource = createSettingsRead<number>();
  const pending = Promise.withResolvers<number>();
  const old = resource.read(() => pending.promise, "SETTINGS_INITIAL_READ_UNAVAILABLE").catch((error: unknown) => error);
  resource.accept(9); pending.resolve(8); assert.ok(await old instanceof Error); assert.equal(resource.snapshot().value, 9);
});
it("aborts an unfinished read when its owner leaves, keeps the retained value and lets a re-entry read afresh", async () => {
  const resource = createSettingsRead<number>(); resource.accept(5);
  const controller = new AbortController(); let seen: AbortSignal | undefined;
  const first = resource.read(signal => { seen = signal; return new Promise<number>(() => undefined); }, "SETTINGS_INITIAL_READ_UNAVAILABLE", undefined, controller.signal).catch((error: unknown) => error);
  controller.abort();
  assert.equal(seen?.aborted, true);
  assert.equal(resource.snapshot().state, "loaded"); assert.equal(resource.snapshot().value, 5);
  assert.equal(await resource.read(() => Promise.resolve(6), "SETTINGS_INITIAL_READ_UNAVAILABLE"), 6);
  assert.ok(await first instanceof Error);
});
it("bounds one client's kept reads, forgetting the least recently used idle read first", () => {
  const client = {}, authority = {};
  const first = settingsReadResource<number>(client, authority, "c", "read-0");
  first.accept(0);
  const shown = settingsReadResource<number>(client, authority, "c", "read-1");
  shown.accept(1);
  const unsubscribe = shown.subscribe(() => undefined);
  for (let index = 2; index <= SETTINGS_READS_LIMIT; index += 1) settingsReadResource<number>(client, authority, "c", `read-${String(index)}`).accept(index);
  assert.equal(settingsReadResource<number>(client, authority, "c", "read-0").snapshot().value, undefined, "the oldest idle read is forgotten");
  assert.equal(first.snapshot().state, "idle");
  assert.equal(settingsReadResource<number>(client, authority, "c", "read-1"), shown, "a read on screen is never evicted");
  assert.equal(shown.snapshot().value, 1);
  unsubscribe();
});
it("a stream reset forgets kept reads nothing shows, and reads the one on screen again, showing nothing from before it", async () => {
  const client = {}, authority = {};
  const kept = settingsReadResource<number>(client, authority, "c", "kept");
  kept.accept(1);
  const shown = settingsReadResource<number>(client, authority, "c", "shown");
  let served = 2;
  const unsubscribe = shown.subscribe(() => undefined);
  assert.equal(await shown.read(async () => served, "SETTINGS_INITIAL_READ_UNAVAILABLE"), 2);
  const stale = shown.stale();
  served = 3;
  dropKeptResults(client);
  assert.equal(kept.snapshot().state, "idle");
  assert.notEqual(settingsReadResource<number>(client, authority, "c", "kept"), kept);
  assert.equal(settingsReadResource<number>(client, authority, "c", "shown"), shown);
  assert.equal(shown.snapshot().state, "loading");
  assert.equal(shown.snapshot().value, undefined, "nothing read before the reset shows after it");
  assert.equal(shown.stale(), stale + 1);
  await vi.waitFor(() => assert.deepEqual(shown.snapshot(), { state: "loaded", value: 3 }));
  unsubscribe();
});
