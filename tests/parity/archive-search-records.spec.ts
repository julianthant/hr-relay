import { expect, test } from '@playwright/test';
import { ensureParityBundle, PARITY_DIST_DIR } from './helpers/bundle.js';
import { assertThemeApplied, installTheme, PARITY_THEMES } from './helpers/capture.js';
import { startFixtureServer } from './helpers/fixture-bff.js';
import { chooseSelect } from './helpers/select-choice.js';

for (const theme of PARITY_THEMES) for (const width of [1024, 1440]) {
 test(`Archive search opens exact runs across versions and workflows @ ${theme.attribute}-${width}`, async ({ page }, info) => {
  ensureParityBundle();
  const server = await startFixtureServer({ distDir: PARITY_DIST_DIR, bundle: { proof: 'working-tree' } });
  const errors: string[] = [], writes: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (request.method() !== 'GET') writes.push(new URL(request.url()).pathname); });
  try {
   await page.setViewportSize({ width, height: width === 1024 ? 720 : 1000 });
   await installTheme(page, theme);
   await page.goto(`${server.baseUrl}/?settings=archive`);
   const archive = page.getByRole('region', { name: 'Archive', exact: true });
   const input = archive.getByRole('textbox', { name: 'Search saved reports', exact: true });
   const results = archive.getByRole('region', { name: 'Archived run search results', exact: true });
   const first = { id: 'archive-demo-run-48216', document: 'DEMO-DOC-48216', employeeId: 'DEMO-1042' };
   const older = { id: 'archive-demo-run-48232', number: 48232, document: 'DEMO-DOC-48232', employeeId: 'DEMO-1058', file: 'request-48232.txt' };
   await input.fill('Jordan');
   await expect(results.getByRole('link')).toHaveCount(2);
   await expect(archive.getByRole('button', { name: 'Reset filters', exact: true })).toHaveCount(0);
   await expect(archive.locator('.mock-archive-version-groups')).toHaveCount(0);
   await expect(results.getByRole('link').nth(1)).toContainText('Dashboard 1.2');
   await expect(results.getByRole('link').nth(1)).toContainText(`Run ${older.number}`);
   const exactHref = (await results.getByRole('link').nth(1).getAttribute('href'))!;
   const params = new URL(exactHref, server.baseUrl).searchParams;
   expect(params.get('archive')).toBe(older.id);
   expect(JSON.parse(params.get('archiveBrowse')!)).toEqual({ filters: { search: 'Jordan' } });
   expect(params.has('archiveWorkflow')).toBe(false);
   expect(params.has('archiveDashboard')).toBe(false);
   await assertThemeApplied(page, theme);
   expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width);
   await info.attach(`archive-search-${theme.attribute}-${width}.png`, { body: await page.screenshot(), contentType: 'image/png' });
   await info.attach(`archive-search-${theme.attribute}-${width}.yml`, { body: await archive.ariaSnapshot(), contentType: 'text/yaml' });
   await input.press('ArrowDown');
   await expect(results.getByRole('link').first()).toBeFocused();
   await page.keyboard.press('ArrowUp');
   await expect(input).toBeFocused();
   await input.press('ArrowDown');
   await page.keyboard.press('ArrowDown');
   await expect(results.getByRole('link').nth(1)).toBeFocused();
   await page.keyboard.press('Enter');
   const report = archive.getByRole('article', { name: 'Saved run report', exact: true });
   await expect(report).toContainText(older.employeeId);
   await expect(report).toContainText(older.document);
   await expect(report.getByRole('heading', { level: 1 })).toBeFocused();
   await expect(page).toHaveURL(new RegExp(`archive=${older.id}`, 'u'));
   const breadcrumb = archive.getByRole('navigation', { name: 'Archive breadcrumbs', exact: true });
   await breadcrumb.getByRole('button', { name: 'Archive', exact: true }).click();
   await expect(input).toHaveValue('Jordan');
   await expect(results.getByRole('link').nth(1)).toBeFocused();
   await page.goto(`${server.baseUrl}/${exactHref}`);
   await page.reload();
   await expect(report).toContainText(older.document);
   await breadcrumb.getByRole('button', { name: 'Archive', exact: true }).click();
   await expect(input).toHaveValue('Jordan');
   for (const query of [older.employeeId, older.document, older.file, '  JORDAN   dashboard 1.2 ']) {
    await input.fill(query);
    await expect(results.getByRole('link')).toHaveCount(1);
    await expect(results.getByRole('link')).toHaveAttribute('data-archive-run-id', older.id);
   }
   await input.fill('no matching archived subject');
   await expect(results.getByRole('link')).toHaveCount(0);
   await expect(results).toContainText('No archived runs match.');
   await archive.getByRole('button', { name: 'Clear search', exact: true }).click();
   await expect(input).toBeFocused();
   const version = archive.getByRole('region', { name: 'Dashboard 1.3', exact: true });
   await expect(version).toContainText('16 reports');
   await version.getByRole('button', { name: /^Separations/u }).click();
   await input.fill('Alex');
   await expect(results.getByRole('link')).toHaveCount(2);
   await expect(results.getByRole('link').first()).toContainText('Onboarding');
   await results.getByRole('link').first().click();
   await expect(report).toContainText('DEMO-DOC-48217');
   const openedParams = new URL(page.url()).searchParams;
   expect(openedParams.get('archive')).toBe('archive-demo-run-48217');
   expect(openedParams.has('archiveDashboard')).toBe(false);
   expect(openedParams.has('archiveWorkflow')).toBe(false);
   await expect(archive.getByRole('alert')).toHaveCount(0);
   await breadcrumb.getByRole('button', { name: 'Archive', exact: true }).click();
   await expect(input).toHaveValue('Alex');
   await input.fill('Jordan');
   await chooseSelect(archive.getByRole('combobox', { name: 'Archived outcome', exact: true }), 'failed');
   await expect(results.getByRole('link')).toHaveCount(0);
   await chooseSelect(archive.getByRole('combobox', { name: 'Archived outcome', exact: true }), 'all');
   await input.fill('Sofia');
   await expect(results.getByRole('link')).toHaveCount(2);
   expect(await results.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true);
   await input.fill(first.document);
   await input.press('Enter');
   await expect(report).toContainText(first.employeeId);
   expect(errors).toEqual([]);
   expect(writes).toEqual([]);
  } finally { await server.close(); }
 });
}
