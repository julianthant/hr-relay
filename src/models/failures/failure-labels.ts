/** Whether a failure code is left to the Explorer's unlisted-failure line. */
export function isUnlistedStorageFailure(code: string): boolean {
  const registered = ErrorCatalogCodeSchema.safeParse(code);
  return registered.success && UNLISTED_STORAGE_FAILURES.has(registered.data);
}

/** The short label of a failure outcome, or `undefined` when its code has none. */
export function operatorFailureLabel(code: string): string | undefined {
  const registered = ErrorCatalogCodeSchema.safeParse(code);
  return registered.success ? FAILURE_LABELS[registered.data] : undefined;
}
