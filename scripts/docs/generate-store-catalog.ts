/** Derived from `taskStoreRegistry` so reuse data cannot go stale; an unreadable shape fails instead of rendering a placeholder. */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { readPendingImplBindings } from "../../src/backend/app/registries/workflow-registry.js";
import { taskStoreRegistry } from "../../src/backend/app/registries/task-registry.js";

export const STORE_CATALOG_DOC_PATH = "docs/rebuild/reference/stores.md";
export const STORE_CATALOG_START_MARKER = "<!-- store-catalog:start -->";
export const STORE_CATALOG_END_MARKER = "<!-- store-catalog:end -->";
export const STORE_CATALOG_LAST_UPDATED_LINE =
  "> **Last updated:** §2 is generated by `npm run stores:catalog` from `src/backend/app/registries/task-registry.ts`;"
  + " `npm run stores:catalog:check` fails on stale bytes. §1, §2b, §3 and §4 are hand-written.";

const LAST_UPDATED_PATTERN = /^> \*\*Last updated:\*\* .*$/m;

/** The structural view this generator needs. `taskStoreRegistry` satisfies it. */
export interface StoreCatalogSessionNeed {
  readonly system: string;
  readonly access: string;
}
export interface StoreCatalogTaskContract {
  readonly id: string;
  readonly title: string;
  readonly effect: "read" | "prepare" | "commit";
  readonly input: unknown;
  readonly output: unknown;
  readonly providers?: readonly string[] | undefined;
  readonly freshness?: { readonly defaultMaxAgeMs: number } | undefined;
}
export interface StoreCatalogTask {
  readonly contract: StoreCatalogTaskContract;
  readonly impl: { readonly sessions: readonly StoreCatalogSessionNeed[] };
}
export interface StoreCatalogStore {
  readonly kind: "browser" | "headless";
  readonly namespace: string;
  readonly driver?: { readonly status: string } | undefined;
  readonly tasks: Readonly<Record<string, StoreCatalogTask>>;
}
export interface StoreCatalogRegistry {
  readonly stores: readonly StoreCatalogStore[];
}
export interface StoreCatalogPendingBindings {
  readonly tasks: readonly {
    readonly taskId: string;
    readonly workflowId: string;
    readonly note: string;
  }[];
}

interface ZodLikeDef {
  readonly type?: unknown;
  readonly discriminator?: unknown;
  readonly options?: unknown;
  readonly values?: unknown;
}

function isUnknownArray(value: unknown): value is readonly unknown[] {
  return Array.isArray(value);
}

/** One own/inherited property of an unknown container, kept `unknown` rather than `any`. */
function propertyOf(container: unknown, key: string): unknown {
  if (container === null || typeof container !== "object") return undefined;
  const value: unknown = Reflect.get(container, key);
  return value;
}

function zodDef(schema: unknown): ZodLikeDef | undefined {
  const def = propertyOf(schema, "def");
  if (def === null || typeof def !== "object") return undefined;
  return def;
}

function zodTypeName(schema: unknown): string {
  const type = zodDef(schema)?.type;
  return typeof type === "string" ? type : "unreadable";
}

function objectShapeKeys(schema: unknown): readonly string[] | undefined {
  if (zodTypeName(schema) !== "object") return undefined;
  const shape = propertyOf(schema, "shape");
  if (shape === null || typeof shape !== "object") return undefined;
  return Object.keys(shape);
}

function unionOptions(schema: unknown): readonly unknown[] | undefined {
  if (zodTypeName(schema) !== "union") return undefined;
  const options = zodDef(schema)?.options;
  if (!isUnknownArray(options) || options.length === 0) return undefined;
  return options;
}

/** The single value of a one-value zod literal, JSON-rendered; undefined for anything else. */
function singleLiteralValue(schema: unknown): string | undefined {
  if (zodTypeName(schema) !== "literal") return undefined;
  const values = zodDef(schema)?.values;
  if (!isUnknownArray(values) || values.length !== 1) return undefined;
  return JSON.stringify(values[0]);
}

function shapeFailure(taskId: string, role: string, schema: unknown): Error {
  return new Error(
    `${taskId} ${role} schema shape is unreadable (zod type "${zodTypeName(schema)}");`
    + " the store catalog refuses to render a placeholder for a shape it cannot derive",
  );
}

function unionDiscriminant(options: readonly unknown[], keysPerArm: readonly (readonly string[])[]): string | undefined {
  const firstArm = keysPerArm[0];
  if (firstArm === undefined) return undefined;
  const candidates = firstArm.filter((key) => keysPerArm.every((keys) => keys.includes(key)));
  for (const key of candidates) {
    const values: string[] = [];
    let literalEverywhere = true;
    for (const option of options) {
      const literal = singleLiteralValue(propertyOf(propertyOf(option, "shape"), key));
      if (literal === undefined) {
        literalEverywhere = false;
        break;
      }
      values.push(literal);
    }
    if (literalEverywhere && new Set(values).size === values.length) return key;
  }
  return undefined;
}

function renderKeyList(keys: readonly string[]): string {
  return keys.length === 0 ? "(no fields)" : keys.map((key) => `\`${key}\``).join(", ");
}

/** Top-level keys of an object schema, or the per-arm keys of a union. Throws on anything else. */
export function renderSchemaKeys(schema: unknown, taskId: string, role: "input" | "output"): string {
  const objectKeys = objectShapeKeys(schema);
  if (objectKeys !== undefined) return renderKeyList(objectKeys);

  const options = unionOptions(schema);
  if (options === undefined) throw shapeFailure(taskId, role, schema);

  const keysPerArm = options.map((option) => {
    const keys = objectShapeKeys(option);
    if (keys === undefined) throw shapeFailure(taskId, `${role} union arm`, option);
    return keys;
  });
  const discriminantKey = zodDefDiscriminator(schema) ?? unionDiscriminant(options, keysPerArm);
  if (discriminantKey === undefined) {
    return keysPerArm.map((keys) => `[${renderKeyList(keys)}]`).join(" / ");
  }
  return options.map((option, index) => {
    const keys = keysPerArm[index] ?? [];
    const literal = singleLiteralValue(propertyOf(propertyOf(option, "shape"), discriminantKey));
    if (literal === undefined) throw shapeFailure(taskId, `${role} union discriminant`, option);
    const rest = keys.filter((key) => key !== discriminantKey);
    return `\`${discriminantKey}=${literal}\`${rest.length === 0 ? "" : ` + ${renderKeyList(rest)}`}`;
  }).join(" / ");
}

function zodDefDiscriminator(schema: unknown): string | undefined {
  const discriminator = zodDef(schema)?.discriminator;
  return typeof discriminator === "string" ? discriminator : undefined;
}

/** The task id's verb — the segment before the first dash of the id's last path element. */
export function taskVerbOf(taskId: string): string {
  const tail = taskId.slice(taskId.lastIndexOf("/") + 1);
  const verb = tail.split("-")[0];
  if (verb === undefined || verb.length === 0) throw new Error(`${taskId} carries no task verb`);
  return verb;
}

function freshnessLabel(contract: StoreCatalogTaskContract, taskId: string): string {
  if (contract.effect !== "read") return "—";
  const policy = contract.freshness;
  if (policy === undefined) throw new Error(`${taskId} is a read task with no freshness policy`);
  const ms = policy.defaultMaxAgeMs;
  if (ms === Number.POSITIVE_INFINITY) return "∞";
  if (ms === 0) return "0 (re-read every run)";
  if (ms % 3_600_000 === 0) return `${ms / 3_600_000}h`;
  if (ms % 60_000 === 0) return `${ms / 60_000}m`;
  if (ms % 1_000 === 0) return `${ms / 1_000}s`;
  return `${ms}ms`;
}

function sessionLabel(task: StoreCatalogTask): string {
  const { sessions } = task.impl;
  if (sessions.length === 0) return "— (sessionless)";
  return sessions.map(({ system, access }) => `\`${system}\` (${access})`).join(", ");
}

function capabilityLabel(contract: StoreCatalogTaskContract): string {
  const providers = contract.providers ?? [];
  return providers.length === 0 ? "—" : providers.map((id) => `\`${id}\``).join(", ");
}

function escapeCell(text: string): string {
  return text.replaceAll("|", "\\|").replaceAll(/\s+/gu, " ").trim();
}

function storeKindLabel(store: StoreCatalogStore): string {
  if (store.kind === "browser") return "browser store";
  return store.namespace.startsWith("workflow:") ? "workflow mini-store" : "service store";
}

function storeHeader(store: StoreCatalogStore, tasks: readonly StoreCatalogTask[]): string {
  const counts = (["read", "prepare", "commit"] as const)
    .map((effect) => `${tasks.filter(({ contract }) => contract.effect === effect).length} ${effect}`)
    .join(" · ");
  const browserSystem = store.kind === "browser" ? `\`${store.namespace}\`` : "none (sessionless)";
  const driver = store.driver === undefined ? "none" : `\`${store.driver.status}\``;
  return `**Kind:** ${storeKindLabel(store)} · **Browser system:** ${browserSystem}`
    + ` · **Driver declaration:** ${driver} · **Tasks:** ${tasks.length} (${counts})`;
}

const TABLE_HEADER = [
  "| Contract id | Title | Effect | Verb | Session | Capability | Inputs | Outputs | Freshness | Status |",
  "|---|---|---|---|---|---|---|---|---|---|",
];

/** Pure: identical registry input renders identical bytes, with no clock and no paths. */
export function renderStoreCatalogSection(
  registry: StoreCatalogRegistry,
  pendingBindings: StoreCatalogPendingBindings,
): string {
  const pendingIds = new Set(pendingBindings.tasks.map(({ taskId }) => taskId));
  const lines: string[] = [
    "<!-- GENERATED by `npm run stores:catalog`. Edit the owning store implementation, not this block. -->",
    "",
  ];
  let taskTotal = 0;
  const storeBlocks: string[] = [];
  for (const store of registry.stores) {
    const tasks = Object.values(store.tasks);
    taskTotal += tasks.length;
    const block: string[] = [`### \`${store.namespace}\``, "", storeHeader(store, tasks), ""];
    if (tasks.length === 0) {
      block.push("_No tasks registered — this store is a declaration-only placeholder._");
    } else {
      block.push(...TABLE_HEADER);
      for (const task of tasks) {
        const { contract } = task;
        const id = contract.id;
        if (pendingIds.has(id)) {
          throw new Error(
            `${id} is registered in the ${store.namespace} store and also listed in the pending-impl bindings;`
            + " a bound contract must be removed from src/backend/app/registries/pending-impl-bindings.json in the same commit",
          );
        }
        block.push([
          "",
          `\`${id}\``,
          escapeCell(contract.title),
          contract.effect,
          taskVerbOf(id),
          sessionLabel(task),
          capabilityLabel(contract),
          renderSchemaKeys(contract.input, id, "input"),
          renderSchemaKeys(contract.output, id, "output"),
          freshnessLabel(contract, id),
          "bound",
          "",
        ].join(" | ").trim());
      }
    }
    storeBlocks.push(block.join("\n"));
  }
  lines.push(
    `_${registry.stores.length} registered stores · ${taskTotal} bound tasks · `
    + `${pendingBindings.tasks.length} pending contracts._`,
    "",
  );
  lines.push(storeBlocks.join("\n\n"), "");
  lines.push("### Pending contracts (declared by a descriptor, no store implementation)", "");
  if (pendingBindings.tasks.length === 0) {
    lines.push(
      "_None — every descriptor contract resolves to a registered store task"
      + " (`src/backend/app/registries/pending-impl-bindings.json`)._",
    );
  } else {
    lines.push(
      "| Contract id | Workflow | Note | Status |",
      "|---|---|---|---|",
      ...pendingBindings.tasks.map(({ taskId, workflowId, note }) =>
        `| \`${taskId}\` | \`${workflowId}\` | ${escapeCell(note)} | pending |`),
    );
  }
  return lines.join("\n");
}

/** Splices a rendered section between the doc's markers and refreshes its "Last updated" line. */
export function applyStoreCatalogSection(markdown: string, section: string): string {
  const start = markdown.indexOf(STORE_CATALOG_START_MARKER);
  const end = markdown.indexOf(STORE_CATALOG_END_MARKER);
  if (start < 0) throw new Error(`${STORE_CATALOG_DOC_PATH} is missing ${STORE_CATALOG_START_MARKER}`);
  if (end < start) throw new Error(`${STORE_CATALOG_DOC_PATH} markers are absent or out of order`);
  const head = markdown.slice(0, start + STORE_CATALOG_START_MARKER.length);
  if (!LAST_UPDATED_PATTERN.test(head)) {
    throw new Error(`${STORE_CATALOG_DOC_PATH} is missing its "> **Last updated:**" header line`);
  }
  const stamped = head.replace(LAST_UPDATED_PATTERN, STORE_CATALOG_LAST_UPDATED_LINE);
  return `${stamped}\n\n${section}\n\n${markdown.slice(end)}`;
}

function main(): void {
  const repoRoot = resolve(import.meta.dirname, "../..");
  const target = resolve(repoRoot, STORE_CATALOG_DOC_PATH);
  const section = renderStoreCatalogSection(taskStoreRegistry, readPendingImplBindings(repoRoot));
  const current = readFileSync(target, "utf8");
  const next = applyStoreCatalogSection(current, section);
  if (process.argv.includes("--check")) {
    if (next !== current) {
      process.stderr.write(`${STORE_CATALOG_DOC_PATH} store catalog is stale — run \`npm run stores:catalog\`.\n`);
      process.exit(1);
    }
    process.stdout.write(`${STORE_CATALOG_DOC_PATH} store catalog is current.\n`);
    return;
  }
  writeFileSync(target, next, "utf8");
  process.stdout.write(`Wrote ${STORE_CATALOG_DOC_PATH} store catalog.\n`);
}

const entry = process.argv[1];
if (entry !== undefined && resolve(entry) === resolve(import.meta.filename)) main();
